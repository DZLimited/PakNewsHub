const NEWEST_OFFSET_MS = 10 * 60 * 1000; // newest story appears "10m ago"

export function rebaseToNow(list, now = Date.now()) {
  const newest = Math.max(...list.map(a => Date.parse(a.publishedAt)));
  const shift = now - NEWEST_OFFSET_MS - newest;
  return list.map(a => ({
    ...a,
    publishedAt: new Date(Date.parse(a.publishedAt) + shift).toISOString(),
  }));
}
